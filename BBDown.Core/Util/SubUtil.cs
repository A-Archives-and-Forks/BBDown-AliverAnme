    private static async Task<List<Subtitle>?> GetIntlSubtitlesFromApi1Async(string aid, string cid, string epId, int index)
    {
        try
        {
            List<Subtitle> subtitles = new();
            string api = "https://" + (Config.Current.EpHost == "api.bilibili.com" ? "api.biliintl.com" : Config.Current.EpHost) + $"/intl/gateway/web/v2/subtitle?episode_id={epId}";
            string json = await HTTPUtil.GetWebSourceAsync(api);
            using var infoJson = JsonDocument.Parse(json);
            var subs = infoJson.RootElement.GetPropertySafe("data").EnumerateArraySafe("subtitles");
            foreach (var sub in subs)
            {
                var lan = sub.GetValueAsStringSafe("lang_key");
                var url = sub.GetValueAsStringSafe("url");
                // 空 URL 的条目无法下载：跳过该条目而不是抛异常。
                // 此前的 ArgumentException 不在本方法 catch 过滤内，会一路抛出并终止整个下载。
                if (string.IsNullOrEmpty(url)) continue;
                Subtitle subtitle = new()
                {
                    url = url,
                    lan = lan,
                    path = $"{aid}/{aid}.{cid}.{lan}{(url.Contains(".json") ? ".srt" : ".ass")}"
                };

                subtitles.Add(subtitle);
            }
            return subtitles;
        }
        catch (Exception ex) when (ex is HttpRequestException or JsonException or KeyNotFoundException)
        {
            Logger.LogDebug("GetIntlSubtitlesFromApi1 failed: {0}", ex.Message);
            return null;
        }
    }

    private static async Task<List<Subtitle>?> GetIntlSubtitlesFromApi2Async(string aid, string cid, string epId, int index)
    {
        try
        {
            List<Subtitle> subtitles = new();
            string api = "https://" + (Config.Current.Host == "api.bilibili.com" ? "api.bilibili.tv" : Config.Current.Host) +
                         $"/intl/gateway/v2/ogv/view/app/season?ep_id={epId}&platform=android&s_locale=zh_SG" + (Config.Current.Token != "" ? $"&access_key={Config.Current.Token}" : "");
            string json = await HTTPUtil.GetWebSourceAsync(api);
            using var infoJson = JsonDocument.Parse(json);
            var modules = infoJson.RootElement.GetPropertySafe("result").GetPropertySafe("modules");
            if (modules.GetArrayLength() == 0) return null;
            var episodes = modules[0].GetPropertySafe("data").GetPropertySafe("episodes");
            if (index < 1 || index > episodes.GetArrayLength()) return null;
            var subs = episodes[index - 1].EnumerateArraySafe("subtitles");
            foreach (var sub in subs)
            {
                var lan = sub.GetValueAsStringSafe("key");
                var url = sub.GetValueAsStringSafe("url").Replace("\\\\/", "/");
                Subtitle subtitle = new()
                {
                    url = url,
                    lan = lan,
                    path = $"{aid}/{aid}.{cid}.{lan}{(url.Contains(".json") ? ".srt" : ".ass")}"
                };

                //有空的URL 不合法
                if (subtitles.Any(s => string.IsNullOrEmpty(s.url)))
                    throw new ArgumentException("Bad url");

                subtitles.Add(subtitle);
            }
            return subtitles;
        }
        catch (Exception ex) when (ex is HttpRequestException or JsonException or KeyNotFoundException)
        {
            Logger.LogDebug("GetIntlSubtitlesFromApi2 failed: {0}", ex.Message);
            return null;
        }
    }

