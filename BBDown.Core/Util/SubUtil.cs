    public static async Task<List<Subtitle>> GetSubtitlesAsync(string aid, string cid, string epId, int index, bool intl)
    {
        List<Subtitle>? subtitles = new();
        if (intl)
        {
            subtitles = await GetIntlSubtitlesFromApi1Async(aid, cid, epId, index) ?? await GetIntlSubtitlesFromApi2Async(aid, cid, epId, index);
        }
        else
        {
            if (Config.Current.Cookie == "")
            {
                subtitles = await GetSubtitlesFromApi3Async(aid, cid, epId, index); // 未登录只有APP可以拿到字幕了
            }
            else
            {
                subtitles = await GetSubtitlesFromApi2Async(aid, cid, epId, index)
                            ?? await GetSubtitlesFromApi1Async(aid, cid, epId, index)
                            ?? await GetSubtitlesFromApi3Async(aid, cid, epId, index);
            }

        }

        if (subtitles == null)
        {
            return new List<Subtitle>(); //返回空列表
        }

        //修正 url 协议
        foreach (var item in subtitles)
        {
            if (item.url.StartsWith("//")) item.url = "https:" + item.url;
        }

        return subtitles;
    }

    public static async Task SaveSubtitleAsync(string url, string path)
    {
        if (path.EndsWith(".srt"))
            await File.WriteAllTextAsync(path, ConvertSubFromJson(await HTTPUtil.GetWebSourceAsync(url)), Encoding.UTF8);
        else
            await File.WriteAllTextAsync(path, await HTTPUtil.GetWebSourceAsync(url), Encoding.UTF8);
    }

    private static string ConvertSubFromJson(string jsonString)
    {
        StringBuilder lines = new();
        using var json = JsonDocument.Parse(jsonString);
        var sub = json.RootElement.EnumerateArraySafe("body").ToList();
        for(int i = 0; i < sub.Count; i++)
        {
            var line = sub[i];
            lines.AppendLine((i + 1).ToString());
            if (line.TryGetProperty("from", out JsonElement from))
            {
                lines.AppendLine($"{FormatTime(from.GetDouble())} --> {FormatTime(line.GetDoubleSafe("to"))}");
            }
            else
            {
                lines.AppendLine($"{FormatTime(0.0)} --> {FormatTime(line.GetDoubleSafe("to"))}");
            }
            //有的没有内容
            if (line.TryGetProperty("content", out JsonElement content))
                lines.AppendLine(SanitizeSrtContent(content.ToString()));
            lines.AppendLine();
        }
        return lines.ToString();
    }

    /// <summary>
    /// 按 SRT 的 <c>HH:MM:SS,mmm</c> 输出时间轴。
    /// 不能用 <c>hh</c> 格式符：它取的是 TimeSpan.Hours（0-23），
    /// 超过 24 小时的时间会丢掉天数——86400 秒会变成 00:00:00，
    /// 让超长视频的字幕整体跳回开头。SRT 本身允许小时数超过 24。
    /// 负数时间在 SRT 中无意义，夹紧到 0，否则符号会被格式化悄悄丢弃。
    /// </summary>
    internal static string FormatTime(double sec) //64.13
    {
        if (double.IsNaN(sec) || sec < 0) sec = 0;
        // 防御畸形时间值：TimeSpan.FromSeconds 对超出 TimeSpan.MaxValue 的输入抛
        // OverflowException，字幕 JSON 里异常的时间字段不应让格式转换直接崩溃。
        // TotalHours 转 long 而非 int：超长视频的小时数可能超过 int 范围。
        if (sec > TimeSpan.MaxValue.TotalSeconds) sec = TimeSpan.MaxValue.TotalSeconds;
        var ts = TimeSpan.FromSeconds(sec);
        return $"{(long)ts.TotalHours:D2}:{ts.Minutes:D2}:{ts.Seconds:D2},{ts.Milliseconds:D3}";
    }

    /// <summary>
    /// 中和字幕正文里会破坏 SRT 块结构的字符。
    /// SRT 用空行分隔字幕块：正文中一旦出现空行，后续所有字幕都会错位。
    /// 多行正文本身合法，因此只折叠空行而不是删除全部换行。
    /// </summary>
    internal static string SanitizeSrtContent(string? content)
    {
        if (string.IsNullOrEmpty(content)) return string.Empty;

        var normalized = content.Replace("\r\n", "\n").Replace('\r', '\n');
        var keptLines = normalized
            .Split('\n')
            .Select(l => l.TrimEnd())
            .Where(l => l.Length > 0);

        return string.Join('\n', keptLines);
    }

